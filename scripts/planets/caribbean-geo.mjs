// Jamaica and Puerto Rico across the middle, the Lesser Antilles curving
// down the east to Trinidad, the Yucatán and the Main round the west and
// south.
//
// LANDS   { name, kind: 'island' | 'mainland', pts: [[lat, lon]…], hills?: 0…1, dry?: 0…1 }
